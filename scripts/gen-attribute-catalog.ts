import "@harness/core";
import {
  getAttrMeta,
  listLogDefinitions,
  listSpanDefinitions,
  SEMCONV_VERSION,
  type AttrMeta,
  type LogRecordDefinition,
  type SpanDefinition,
  type SpanDefinitionShape,
  type LogRecordShape,
} from "@harness/telemetry";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

type CatalogSpanDefinition = Pick<
  SpanDefinition<SpanDefinitionShape>,
  "name" | "shape" | "ownerTask"
>;

type CatalogLogDefinition = Pick<LogRecordDefinition, "name" | "shape">;
type CatalogShape = SpanDefinitionShape | LogRecordShape;

function compareNames(left: string, right: string): number {
  if (left < right) {
    return -1;
  }
  if (left > right) {
    return 1;
  }
  return 0;
}

function attributeType(meta: AttrMeta): string {
  switch (meta.kind) {
    case "id":
      return "Id";
    case "code":
      return "Code";
    case "hash":
      return "SHA-256 hash";
    case "enum":
      return `enum: ${(meta.values ?? []).map((value) => `\`${value}\``).join(", ")}`;
    case "int":
      return "integer";
    case "num":
      return "finite number";
    case "bool":
      return "boolean";
  }
}

function renderAttributeTable(name: string, shape: CatalogShape, packageName: string): string {
  const rows = Object.keys(shape)
    .sort(compareNames)
    .map((attributeName) => {
      const schema: unknown = Reflect.get(shape, attributeName);
      const meta = getAttrMeta(schema);
      if (meta === undefined) {
        throw new Error(`Attribute metadata is missing for ${name}.${attributeName}.`);
      }
      const presence = meta.optional === true ? "Optional" : "Required";
      return `| \`${attributeName}\` | ${attributeType(meta)} | ${presence} | \`${packageName}\` |`;
    });
  return [
    `### \`${name}\``,
    "",
    "| Attribute | Type | Presence | Owning package |",
    "| --- | --- | --- | --- |",
    ...rows,
  ].join("\n");
}

/**
 * Renders the span and log registry metadata as a deterministic Markdown catalog.
 *
 * @param spans - Registered span definitions to include.
 * @param logs - Registered log definitions to include.
 * @returns Complete Markdown document contents.
 */
export function renderAttributeCatalog(
  spans: readonly CatalogSpanDefinition[],
  logs: readonly CatalogLogDefinition[],
): string {
  const spanSections = [...spans]
    .sort((left, right) => compareNames(left.name, right.name))
    .map((definition) => {
      const table = renderAttributeTable(
        definition.name,
        definition.shape,
        definition.ownerTask.packageName,
      );
      return `${table}\n\nOwner task: \`${definition.ownerTask.taskId}\`.`;
    });
  const logSections = [...logs]
    .sort((left, right) => compareNames(left.name, right.name))
    .map((definition) =>
      renderAttributeTable(definition.name, definition.shape, "@harness/telemetry"),
    );

  return [
    "<!-- Generated by scripts/gen-attribute-catalog.ts. Do not edit directly. -->",
    "",
    "# Telemetry attribute catalog",
    "",
    `OpenTelemetry semantic-conventions version: \`${SEMCONV_VERSION}\`.`,
    "",
    "MCP and GenAI conventions are in development and may change; updating the pinned version requires a deliberate review.",
    "",
    "## Spans",
    "",
    ...(spanSections.length === 0 ? ["_No span definitions._"] : [spanSections.join("\n\n")]),
    "",
    "## Log records",
    "",
    ...(logSections.length === 0 ? ["_No log definitions._"] : [logSections.join("\n\n")]),
    "",
  ].join("\n");
}

/** Returns whether a catalog file matches the generated contents. */
export function isAttributeCatalogCurrent(
  existing: string | undefined,
  generated: string,
): boolean {
  return existing === generated;
}

function main(): void {
  const check = process.argv.slice(2).includes("--check");
  if (process.argv.slice(2).some((argument) => argument !== "--check") || process.argv.length > 3) {
    process.stderr.write("Usage: yarn docs:catalog [--check]\n");
    process.exitCode = 2;
    return;
  }

  const catalogPath = fileURLToPath(
    new URL("../docs/telemetry/attribute-catalog.md", import.meta.url),
  );
  const generated = renderAttributeCatalog(listSpanDefinitions(), listLogDefinitions());
  const existing = existsSync(catalogPath) ? readFileSync(catalogPath, "utf8") : undefined;

  if (check) {
    if (!isAttributeCatalogCurrent(existing, generated)) {
      process.stderr.write(
        "Telemetry attribute catalog is stale. Run `yarn docs:catalog` and commit the result.\n",
      );
      process.exitCode = 1;
    }
    return;
  }

  mkdirSync(dirname(catalogPath), { recursive: true });
  writeFileSync(catalogPath, generated);
}

const scriptPath = process.argv[1];
if (scriptPath !== undefined && import.meta.url === pathToFileURL(scriptPath).href) {
  main();
}
