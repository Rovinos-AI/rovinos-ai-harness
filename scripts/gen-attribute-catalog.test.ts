import { attr, defineLogRecord, defineSpan } from "@harness/telemetry";
import { describe, expect, it } from "vitest";
import { isAttributeCatalogCurrent, renderAttributeCatalog } from "./gen-attribute-catalog.js";

const ownerTask = { taskId: "4.7", packageName: "@harness/telemetry" } as const;
const fixtureSpan = defineSpan(
  "harness.catalog_fixture",
  {
    "harness.fixture.id": attr.id(),
    "harness.fixture.mode": attr.enum(["safe", "fast"]),
    "harness.fixture.count": attr.optional(attr.int()),
    "harness.fixture.enabled": attr.bool(),
  },
  ownerTask,
);
const fixtureLog = defineLogRecord("harness.catalog_fixture_log", {
  "harness.fixture.code": attr.code(),
  "harness.fixture.hash": attr.hash(),
  "harness.fixture.ratio": attr.num(),
});

describe("attribute catalog generator", () => {
  it("renders a stable snapshot for fixture registries", () => {
    expect(renderAttributeCatalog([fixtureSpan], [fixtureLog])).toMatchInlineSnapshot(`
      "<!-- Generated by scripts/gen-attribute-catalog.ts. Do not edit directly. -->

      # Telemetry attribute catalog

      OpenTelemetry semantic-conventions version: \`1.43.0\`.

      MCP and GenAI conventions are in development and may change; updating the pinned version requires a deliberate review.

      ## Spans

      ### \`harness.catalog_fixture\`

      | Attribute | Type | Presence | Owning package |
      | --- | --- | --- | --- |
      | \`harness.error.code\` | Code | Optional | \`@harness/telemetry\` |
      | \`harness.fixture.count\` | integer | Optional | \`@harness/telemetry\` |
      | \`harness.fixture.enabled\` | boolean | Required | \`@harness/telemetry\` |
      | \`harness.fixture.id\` | Id | Required | \`@harness/telemetry\` |
      | \`harness.fixture.mode\` | enum: \`safe\`, \`fast\` | Required | \`@harness/telemetry\` |

      Owner task: \`4.7\`.

      ## Log records

      ### \`harness.catalog_fixture_log\`

      | Attribute | Type | Presence | Owning package |
      | --- | --- | --- | --- |
      | \`harness.fixture.code\` | Code | Required | \`@harness/telemetry\` |
      | \`harness.fixture.hash\` | SHA-256 hash | Required | \`@harness/telemetry\` |
      | \`harness.fixture.ratio\` | finite number | Required | \`@harness/telemetry\` |
      "
    `);
  });

  it("detects drift for check mode without exposing file contents", () => {
    const catalog = renderAttributeCatalog([fixtureSpan], [fixtureLog]);

    expect(isAttributeCatalogCurrent(catalog, catalog)).toBe(true);
    expect(isAttributeCatalogCurrent(`${catalog}stale`, catalog)).toBe(false);
    expect(isAttributeCatalogCurrent(undefined, catalog)).toBe(false);
  });
});
