import { createHash } from "node:crypto";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { attr, defineLogRecord, defineSpan, POLICY_VERSION } from "@rovinos/telemetry";
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import {
  renderCollectorAllowlist,
  runCollectorAllowlistCommand,
} from "./gen-collector-allowlist.js";

const ownerTask = { taskId: "4.6", packageName: "@rovinos/telemetry" } as const;
const alphaSpan = defineSpan(
  "harness.collector_alpha",
  {
    "harness.collector.z": attr.code(),
    "harness.collector.a": attr.id(),
  },
  ownerTask,
);
const zebraSpan = defineSpan(
  "harness.collector_zebra",
  { "harness.collector.value": attr.bool() },
  ownerTask,
);
const alphaLog = defineLogRecord("harness.collector_alpha_log", {
  "harness.collector.code": attr.code(),
});
const zebraLog = defineLogRecord("harness.collector_zebra_log", {
  "harness.collector.value": attr.bool(),
});
const metricAllowlist = {
  "harness.collector.zebra": ["harness.collector.z"],
  "harness.collector.alpha": ["harness.collector.b", "harness.collector.a"],
};

let testDirectory: string;

beforeEach(() => {
  testDirectory = mkdtempSync(join(tmpdir(), "collector-allowlist-"));
});

afterEach(() => {
  rmSync(testDirectory, { recursive: true, force: true });
});

describe("Collector allowlist generator", () => {
  it("matches the committed allowlist SHA-256 policy version", () => {
    const allowlist = readFileSync(
      new URL("../infra/collector/allowlist.generated.yaml", import.meta.url),
      "utf8",
    );
    const digest = createHash("sha256").update(allowlist, "utf8").digest("hex");

    expect(POLICY_VERSION).toBe(`p-${digest.slice(0, 12)}`);
  });

  it("renders a deterministic snapshot for fixture registries", () => {
    expect(renderCollectorAllowlist([zebraSpan, alphaSpan], [zebraLog, alphaLog], metricAllowlist))
      .toMatchInlineSnapshot(`
        "# SPDX-License-Identifier: Apache-2.0
        # Generated by scripts/gen-collector-allowlist.ts. Do not edit directly.
        # The policy version is derived from this file's SHA-256 (task 10.5).
        processors:
          filter/drop_unregistered_spans:
            error_mode: "ignore"
            traces:
              span:
                - "not (name == \\"harness.collector_alpha\\" or name == \\"harness.collector_zebra\\")"
          filter/drop_span_events:
            error_mode: "ignore"
            traces:
              spanevent:
                - "true"
          transform/span_attributes:
            error_mode: "ignore"
            trace_statements:
              - "keep_keys(scope.attributes, [])"
              - "set(span.links, nil)"
              - "keep_keys(span.attributes, [\\"harness.collector.a\\", \\"harness.collector.z\\", \\"harness.error.code\\"]) where span.name == \\"harness.collector_alpha\\""
              - "keep_keys(span.attributes, [\\"harness.collector.value\\", \\"harness.error.code\\"]) where span.name == \\"harness.collector_zebra\\""
              - "set(span.status.message, \\"\\")"
          filter/drop_unregistered_logs:
            error_mode: "ignore"
            logs:
              log_record:
                - "not (body == \\"harness.collector_alpha_log\\" or body == \\"harness.collector_zebra_log\\")"
          transform/log_attributes:
            error_mode: "ignore"
            log_statements:
              - "keep_keys(scope.attributes, [])"
              - "keep_keys(log.attributes, [\\"harness.collector.code\\"]) where log.body == \\"harness.collector_alpha_log\\""
              - "keep_keys(log.attributes, [\\"harness.collector.value\\"]) where log.body == \\"harness.collector_zebra_log\\""
          filter/drop_unregistered_metrics:
            error_mode: "ignore"
            metrics:
              metric:
                - "not (name == \\"harness.collector.alpha\\" or name == \\"harness.collector.zebra\\")"
          transform/metric_attributes:
            error_mode: "ignore"
            metric_statements:
              - "keep_keys(scope.attributes, [])"
              - "keep_keys(exemplar.filtered_attributes, [])"
              - "keep_keys(datapoint.attributes, [\\"harness.collector.a\\", \\"harness.collector.b\\"]) where metric.name == \\"harness.collector.alpha\\""
              - "keep_keys(datapoint.attributes, [\\"harness.collector.z\\"]) where metric.name == \\"harness.collector.zebra\\""
          transform/resource_attributes:
            error_mode: "ignore"
            trace_statements:
              - "keep_keys(resource.attributes, [\\"harness.policy.version\\", \\"service.name\\", \\"service.version\\", \\"telemetry.sdk.language\\", \\"telemetry.sdk.name\\", \\"telemetry.sdk.version\\"])"
            log_statements:
              - "keep_keys(resource.attributes, [\\"harness.policy.version\\", \\"service.name\\", \\"service.version\\", \\"telemetry.sdk.language\\", \\"telemetry.sdk.name\\", \\"telemetry.sdk.version\\"])"
            metric_statements:
              - "keep_keys(resource.attributes, [\\"harness.policy.version\\", \\"service.name\\", \\"service.version\\", \\"telemetry.sdk.language\\", \\"telemetry.sdk.name\\", \\"telemetry.sdk.version\\"])"
        service:
          pipelines:
            traces:
              processors:
                - "memory_limiter"
                - "filter/drop_unregistered_spans"
                - "filter/drop_span_events"
                - "transform/span_attributes"
                - "transform/resource_attributes"
                - "resource/policy_version"
                - "batch"
            logs:
              processors:
                - "memory_limiter"
                - "filter/drop_unregistered_logs"
                - "transform/log_attributes"
                - "transform/resource_attributes"
                - "resource/policy_version"
                - "batch"
            metrics:
              processors:
                - "memory_limiter"
                - "filter/drop_unregistered_metrics"
                - "transform/metric_attributes"
                - "transform/resource_attributes"
                - "resource/policy_version"
                - "batch"
        "
      `);
  });

  it("writes and checks generated output, then fails on drift", () => {
    const allowlistPath = join(testDirectory, "allowlist.generated.yaml");
    const options = {
      allowlistPath,
      policyVersionYamlPath: join(testDirectory, "policy-version.generated.yaml"),
      policyVersionTypescriptPath: join(testDirectory, "policy-version.ts"),
      spans: [alphaSpan],
      logs: [alphaLog],
      metricAllowlist,
    };

    expect(runCollectorAllowlistCommand([], options)).toEqual({ exitCode: 0, stderr: "" });
    const generated = readFileSync(allowlistPath, "utf8");
    expect(runCollectorAllowlistCommand(["--check"], options)).toEqual({
      exitCode: 0,
      stderr: "",
    });

    writeFileSync(allowlistPath, `${generated}stale`);
    const stale = runCollectorAllowlistCommand(["--check"], options);
    expect(stale.exitCode).toBe(1);
    expect(stale.stderr).toContain("first differing line:");
    expect(readFileSync(allowlistPath, "utf8")).toBe(`${generated}stale`);
  });

  it("detects drift in both generated policy-version files", () => {
    const options = {
      allowlistPath: join(testDirectory, "allowlist.generated.yaml"),
      policyVersionYamlPath: join(testDirectory, "policy-version.generated.yaml"),
      policyVersionTypescriptPath: join(testDirectory, "policy-version.ts"),
      spans: [alphaSpan],
      logs: [alphaLog],
      metricAllowlist,
    };
    expect(runCollectorAllowlistCommand([], options).exitCode).toBe(0);

    writeFileSync(options.policyVersionYamlPath, "stale");
    expect(runCollectorAllowlistCommand(["--check"], options).stderr).toContain(
      "policy-version.generated.yaml is stale",
    );
    expect(runCollectorAllowlistCommand([], options).exitCode).toBe(0);

    writeFileSync(options.policyVersionTypescriptPath, "stale");
    expect(runCollectorAllowlistCommand(["--check"], options).stderr).toContain(
      "policy-version.ts is stale",
    );
  });

  it("fails check mode when the generated file is missing", () => {
    const result = runCollectorAllowlistCommand(["--check"], {
      allowlistPath: join(testDirectory, "missing.yaml"),
      policyVersionYamlPath: join(testDirectory, "missing-policy-version.yaml"),
      policyVersionTypescriptPath: join(testDirectory, "missing-policy-version.ts"),
      spans: [],
      logs: [],
      metricAllowlist: {},
    });

    expect(result.exitCode).toBe(1);
    expect(result.stderr).toContain("first differing line: 1");
  });

  it("rejects unsupported command-line arguments", () => {
    expect(
      runCollectorAllowlistCommand(["--unknown"], {
        allowlistPath: join(testDirectory, "unused.yaml"),
        policyVersionYamlPath: join(testDirectory, "unused-policy-version.yaml"),
        policyVersionTypescriptPath: join(testDirectory, "unused-policy-version.ts"),
        spans: [],
        logs: [],
        metricAllowlist: {},
      }),
    ).toEqual({
      exitCode: 2,
      stderr: "Usage: yarn gen:collector [--check]\n",
    });
  });
});
